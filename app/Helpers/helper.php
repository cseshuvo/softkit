    function slug2Title($string): string
    {
        return Str::title(str_replace('-', ' ', $string));
    }
}


if (!function_exists('getFile')) {
    function getFile($image = '', $type = null): string
    {
        $disk = config('filesystems.default');
        $default = !$type ? asset(config('location.placeholder')) : asset(config('location.placeholder_two'));

        try {
            if ($disk == 'public') {
                $localImage = asset('/'.$image) ;
                return !empty($image) && Storage::disk($disk)->exists($image) ? $localImage : $default;
            } else {
                return !empty($image) && Storage::disk($disk)->exists($image) ? Storage::disk($disk)->url($image) : $default;
            }
        } catch (Exception $e) {
            return $default;
        }
    }
}

if (!function_exists('jsonResponse')) {
    function jsonResponse($data, $status = 200, array $extra = []): JsonResponse
    {
        if (is_string($data)) {
            return response()->json(
                array_merge(['message' => $data], $extra),
                $status
            );
        }

        return response()->json($data, $status);
    }
}


if (!function_exists('jsonResponse')) {
    function jsonResponse($data, $status = true, array $extra = []): JsonResponse
    {
        // If passed a string, assume it's a message
        if (is_string($data)) {
            return response()->json([
                'success' => $status,
                'message' => $data,
                ...$extra
            ], $status);
        }

        // If it's an array, return it as-is with success => true
        return response()->json([
            'success' => $status,
            $data,
            ...$extra
        ], $status);
    }
}



if (!function_exists('timeZones')) {
    function timeZones()
    {
        $timezones = [];
        $zones = DateTimeZone::listIdentifiers();

        foreach ($zones as $zone) {
            $dateTime = new DateTime('now', new DateTimeZone($zone));
            $offset = $dateTime->format('P');
            $timezones[$zone] = "(UTC $offset) $zone";
        }

        asort($timezones); 
        return $timezones;
    }
}



